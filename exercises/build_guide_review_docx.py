def shade(cell, color):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tc_pr.append(shd)


def add_table(doc, rows, start):
    table = doc.add_table(rows=1, cols=4)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    widths = (Cm(1.0), Cm(1.6), Cm(6.7), Cm(7.7))
    for cell, text, width in zip(table.rows[0].cells, ("№", "Стр.", "Текущ текст / проблем", "Предложена корекция"), widths):
        cell.text = ""
        run = cell.paragraphs[0].add_run(text)
        run.bold = True
        cell.width = width
        shade(cell, "D9E2F3")
    for i, (page, current, fix) in enumerate(rows, start=start):
        cells = table.add_row().cells
        for cell, text, width in zip(cells, (str(i), page, current, fix), widths):
            cell.text = text
            cell.width = width
    for row in table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                p.paragraph_format.space_after = Pt(0)
                for run in p.runs:
                    run.font.size = Pt(10)
    return start + len(rows)


